"""Extract XBTune definition data from EcmDroid's ecmdroid.db.

Usage: python3 -I tools/extract_ecmdroid_db.py path/to/ecmdroid.db COMMIT > data/ecmdroid.toml

ecmdroid.db is distributed by EcmDroid (https://github.com/ecmdroid/ecmdroid,
app/src/main/assets/ecmdroid.db.gz) under GPL-3.0. EcmDroid states it was
converted from a database dump the ECMSpy maintainer allowed it to use under
GPLv3. See docs/PROVENANCE.md before redistributing the output.

Phase 1 extracts ECM IDs and page layouts only. Variables, tables and bit
fields are added in phase 2.
"""
import sqlite3
import sys

TYPE_TO_FAMILY = {"DDFI": "ddfi1", "DDFI-2": "ddfi2", "DDFI-3": "ddfi3"}


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    db, commit = sys.argv[1], sys.argv[2]
    c = sqlite3.connect(db)
    out = [
        "# GENERATED by tools/extract_ecmdroid_db.py. Do not edit by hand.",
        "#",
        "# Source: EcmDroid ecmdroid.db (app/src/main/assets/ecmdroid.db.gz)",
        f"# EcmDroid commit: {commit}",
        "# License: GPL-3.0. EcmDroid says this database was converted from a",
        "# dump the ECMSpy maintainer allowed it to use under GPLv3.",
        "# Do NOT publish or ship this file until that permission is confirmed",
        "# to cover XBTune. See docs/PROVENANCE.md.",
        "",
        "[source]",
        'name = "ecmdroid.db"',
        f"ecmdroid_commit = {q(commit)}",
        "",
    ]
    rows = c.execute(
        "select name, file, type, size, xsize, poll_len, category, remark from eeprom order by type, name"
    ).fetchall()
    for name, file, typ, size, xsize, poll_len, cat, remark in rows:
        pages = c.execute(
            "select page, size from pages where category = ? order by page", (cat,)
        ).fetchall()
        out += [
            "[[ecm]]",
            f"id = {q(name)}",
            f"definition = {q(file)}",
            f"family = {q(TYPE_TO_FAMILY[typ])}",
            f"size = {size}",
            f"xsize = {xsize}",
            f"runtime_len = {poll_len}",
            f"remark = {q((remark or '').strip())}",
            "pages = [" + ", ".join(f"[{p}, {s}]" for p, s in pages) + "]",
            "",
        ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()

"""Extract XBTune definition data from EcmDroid's ecmdroid.db.

Usage: python3 -I tools/extract_ecmdroid_db.py path/to/ecmdroid.db COMMIT > data/ecmdroid.toml

ecmdroid.db is distributed by EcmDroid (https://github.com/ecmdroid/ecmdroid,
app/src/main/assets/ecmdroid.db.gz) under GPL-3.0. EcmDroid states it was
converted from a database dump the ECMSpy maintainer allowed it to use under
GPLv3. See docs/PROVENANCE.md before redistributing the output.

Output: every ECM ID with its page layout, and for in-scope (DDFI/DDFI-2/DDFI-3)
definitions their EEPROM variables, runtime variables, bit sets and the
display names they reference. Values are copied, not interpreted, except:
- numeric text columns become numbers (NULL is left out);
- names.format ("0", "0.00", ...) becomes a decimal count;
- duplicate (category, varname) rows: the lowest uniqueid wins, and the
  script fails if duplicates disagree on type, size or offset.
"""
import json
import sqlite3
import sys

TYPE_TO_FAMILY = {"DDFI": "ddfi1", "DDFI-2": "ddfi2", "DDFI-3": "ddfi3"}
IN_SCOPE = {"DDFI", "DDFI-2", "DDFI-3"}


def s(v):
    """A TOML basic string. JSON string escapes are valid TOML escapes."""
    return json.dumps("" if v is None else str(v), ensure_ascii=False)


def num(v):
    if v is None or str(v).strip() == "":
        return None
    f = float(v)
    return int(f) if f.is_integer() and "." not in str(v) and "e" not in str(v).lower() else f


def flt(v):
    """A float, always (TOML distinguishes 10 from 10.0)."""
    if v is None or str(v).strip() == "":
        return None
    return float(v)


def decimals(fmt):
    if fmt is None or not fmt.startswith("0"):
        return None
    return len(fmt.split(".", 1)[1]) if "." in fmt else 0


def inline(d):
    parts = []
    for k, v in d.items():
        if v is None:
            continue
        if isinstance(v, bool):
            parts.append(f"{k} = {'true' if v else 'false'}")
        elif isinstance(v, (int, float)):
            parts.append(f"{k} = {v!r}")
        elif isinstance(v, list):
            parts.append(f"{k} = [" + ", ".join(s(x) if isinstance(x, str) or x is None else repr(x) for x in v) + "]")
        else:
            parts.append(f"{k} = {s(v)}")
    return "{ " + ", ".join(parts) + " }"


def dedupe(rows, key, check, conflicts):
    """Drop exact-enough duplicates (lowest uniqueid wins). If duplicates
    disagree on any `check` column, drop ALL rows for that key and record it
    in `conflicts`: EcmDroid would silently pick one, we refuse to guess."""
    groups = {}
    for r in sorted(rows, key=lambda r: r["uniqueid"]):
        groups.setdefault(tuple(r[x] for x in key), []).append(r)
    out = []
    for k, rs in groups.items():
        if any(any(rs[0][c] != r[c] for c in check) for r in rs[1:]):
            conflicts.append((k, [r["uniqueid"] for r in rs]))
            print(f"warning: conflicting rows for {k}: uniqueids {[r['uniqueid'] for r in rs]}; dropped", file=sys.stderr)
            continue
        out.append(rs[0])
    return out


def main():
    db, commit = sys.argv[1], sys.argv[2]
    c = sqlite3.connect(db)
    c.row_factory = sqlite3.Row
    q = lambda sql, *a: [dict(r) for r in c.execute(sql, a)]

    out = [
        "# GENERATED by tools/extract_ecmdroid_db.py. Do not edit by hand.",
        "#",
        "# Source: EcmDroid ecmdroid.db (app/src/main/assets/ecmdroid.db.gz)",
        f"# EcmDroid commit: {commit}",
        "# License: GPL-3.0. EcmDroid says this database was converted from a",
        "# dump the ECMSpy maintainer allowed it to use under GPLv3.",
        "# Do NOT publish or ship this file until that permission is confirmed",
        "# to cover XBTune. See docs/PROVENANCE.md.",
        "",
    ]
    # Tables ([source], [[ecm]]) go last: in TOML, keys after a table header
    # belong to that table, and the variable arrays must be top-level.
    tail = [
        "[source]",
        'name = "ecmdroid.db"',
        f"ecmdroid_commit = {s(commit)}",
        "",
    ]
    ecms = q("select * from eeprom order by type, name")
    for e in ecms:
        pages = q("select page, size from pages where category = ? order by page", e["category"])
        tail += [
            "[[ecm]]",
            f"id = {s(e['name'])}",
            f"definition = {s(e['file'])}",
            f"category = {e['category']}",
            f"family = {s(TYPE_TO_FAMILY[e['type']])}",
            f"size = {e['size']}",
            f"xsize = {e['xsize']}",
            f"runtime_len = {e['poll_len']}",
            f"remark = {s((e['remark'] or '').strip())}",
            "pages = [" + ", ".join(f"[{p['page']}, {p['size']}]" for p in pages) + "]",
            "",
        ]

    cats = sorted({e["category"] for e in ecms if e["type"] in IN_SCOPE})
    ph = ",".join("?" * len(cats))

    conflicts = []
    ee = dedupe(q(f"select * from eeoffsets where category in ({ph})", *cats),
                ("category", "varname"), ("type", "size", "offset"), conflicts)
    out.append("eeprom_vars = [")
    for r in sorted(ee, key=lambda r: (r["category"], r["offset"], r["varname"])):
        out.append("  " + inline({
            "c": r["category"], "var": r["varname"], "type": r["type"],
            "size": r["size"], "offset": r["offset"],
            "scale": flt(r["scale"]), "translate": flt(r["translate"]),
            "elemsize": r["elemsize"], "cols": r["cols"], "rows": r["rows"], "skip": r["skip"],
            "axis_scale": flt(r["axisscale"]), "axis_translate": flt(r["axistranslate"]),
            "xaxis": r["xaxis"] or None, "yaxis": r["yaxis"] or None,
        }) + ",")
    out += ["]", ""]

    rt = dedupe(q(f"select * from rtoffsets where category in ({ph})", *cats),
                ("category", "varname"), ("type", "size", "offset"), conflicts)
    out.append("# Variables with conflicting duplicate rows in ecmdroid.db, left out.")
    out.append("conflicts = [" + ", ".join(inline({"c": k[0], "var": k[1], "uniqueids": ids}) for k, ids in conflicts) + "]")
    out.append("")
    out.append("runtime_vars = [")
    for r in sorted(rt, key=lambda r: (r["category"], r["offset"], r["varname"])):
        out.append("  " + inline({
            "c": r["category"], "var": r["varname"], "type": r["type"],
            "size": r["size"], "offset": r["offset"],
            "scale": flt(r["scale"]), "translate": flt(r["translate"]),
            "low": flt(r["low"]), "high": flt(r["high"]),
            "ulow": flt(r["ulow"]), "uhigh": flt(r["uhigh"]),
            "secret": bool(r["secret"]),
        }) + ",")
    out += ["]", ""]

    used = {r["varname"] for r in ee} | {r["varname"] for r in rt}
    out.append("bits = [")
    for b in sorted(q("select * from bits"), key=lambda b: b["varname"]):
        if b["varname"] not in used:
            continue
        out.append("  " + inline({
            "var": b["varname"], "name": b["name"], "byte": b["byte"],
            "desc": [b[f"bit{i}"] for i in range(1, 9)],
            "dtc": [b[f"dtc{i}"] for i in range(1, 9)],
            "bitname": [b[f"bitname{i}"] for i in range(1, 9)],
        }).replace("None", '""') + ",")
    out += ["]", ""]

    out.append("names = [")
    for n in sorted(q("select * from names"), key=lambda n: n["varname"]):
        if n["varname"] not in used:
            continue
        out.append("  " + inline({
            "var": n["varname"], "origname": n["origname"], "label": n["name"],
            "remark": n["remark"], "description": n["description"],
            "units": n["units"], "decimals": decimals(n["format"]),
            "axis_units": n["axisunits"], "axis_decimals": decimals(n["axisformat"]),
            "secret": bool(n["secret"]),
        }) + ",")
    out += ["]", ""]
    sys.stdout.write("\n".join(out + tail))


if __name__ == "__main__":
    main()
